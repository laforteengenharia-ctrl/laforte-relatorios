-- Legendas para todo o conjunto de fotos de uma medição, independente da seleção do relatório.
CREATE TABLE IF NOT EXISTS public.foto_legendas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contrato_id bigint NOT NULL,
  frente_id bigint NOT NULL,
  medicao_id bigint NOT NULL,
  drive_arquivo_id text NOT NULL,
  nome_arquivo text,
  legenda text NOT NULL DEFAULT '',
  origem text NOT NULL DEFAULT 'ia' CHECK (origem IN ('ia', 'manual')),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT foto_legendas_medicao_drive_unique UNIQUE (medicao_id, drive_arquivo_id)
);

ALTER TABLE public.foto_legendas ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON public.foto_legendas TO authenticated;

DROP POLICY IF EXISTS foto_legendas_authenticated_select ON public.foto_legendas;
CREATE POLICY foto_legendas_authenticated_select
  ON public.foto_legendas FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS foto_legendas_authenticated_insert ON public.foto_legendas;
CREATE POLICY foto_legendas_authenticated_insert
  ON public.foto_legendas FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS foto_legendas_authenticated_update ON public.foto_legendas;
CREATE POLICY foto_legendas_authenticated_update
  ON public.foto_legendas FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
